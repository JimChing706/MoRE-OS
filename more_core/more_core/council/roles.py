class InMemoryCharterProvider:
    """内存角色章程提供者。"""

    def __init__(
        self,
        core: dict[str, str] | None = None,
        extended: dict[str, str] | None = None,
    ):
        self._core = dict(core or CORE_CHARTERS)
        self._extended = dict(extended or EXTENDED_CHARTERS)

    def get(self, role_id: str) -> str:
        """获取角色章程。"""
        if role_id in self._core:
            return self._core[role_id]
        if role_id in self._extended:
            return self._extended[role_id]
        raise CouncilError(
            f"角色 '{role_id}' 未注册。"
            f" 核心角色: {list(self._core)}; 扩展角色: {list(self._extended)}"
        )

    def register(self, role_id: str, charter: str, kind: str = "extended") -> None:
        """注册新角色。"""
        if kind == "core":
            self._core[role_id] = charter
        else:
            self._extended[role_id] = charter
