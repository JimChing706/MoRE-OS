"""认知角色章程 — 借鉴 ai_council role_charters 设计模式。

为 L4 认知层提供多视角分析角色。每个角色有独立的思维框架和输出风格。
设计原则:
- 5 个核心角色 + 按场景激活的扩展角色
- 角色领土唯一性（避免语义重叠 > 30%）
- 角色章程由配置文件驱动，不硬编码
"""

from __future__ import annotations

from typing import Protocol

from ..core.errors import CouncilError


class RoleCharterProvider(Protocol):
    """角色章程提供者协议。"""

    def get(self, role_id: str) -> str: ...


