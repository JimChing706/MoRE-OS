# 认知风格参数
COGNITIVE_STYLES: dict[str, dict[str, Any]] = {
    "analyst": {
        "style": "冷静系统·注重细节·数据驱动",
        "rhythm": "慢思考，逐层分解",
        "language": "用结构化列表展示分析路径，每个结论附推断依据",
    },
    "architect": {
        "style": "全局视角·长期思维·关注边界",
        "rhythm": "先大后小，架构决策→细节实现",
        "language": "先给架构决策，再逐条解释原因，最后说明可替代方案",
    },
    "critic": {
        "style": "怀疑主义·逻辑严密·精准打击",
        "rhythm": "快速扫描，精准定位漏洞",
        "language": "每项质疑附具体推理链，不人身攻击",
    },
    "pragmatist": {
        "style": "结果导向·关注约束·不容许模糊",
        "rhythm": "快速判断，给出时限和具体数字",
        "language": "用'能否在 X 周内完成 Y'这样的具体表述",
    },
    "innovator": {
        "style": "联想跳跃·打破常规·跨域思考",
        "rhythm": "先发散后收敛",
        "language": "先提激进思路，再逐步收敛到可行范围",
    },
}


def inject_template(charter: str, role_id: str) -> str:
    """将角色的思维模板注入提示词。

    附加在现有角色章程末尾，不覆盖原始内容。
    """
    template = CORE_TEMPLATES.get(role_id)
    style = COGNITIVE_STYLES.get(role_id, {})
    if not template:
        return charter

    extras = [template.strip()]
    if style:
        extras.append(
            f"\n【认知风格】\n风格: {style.get('style', '')}\n"
            f"节奏: {style.get('rhythm', '')}\n"
            f"语言: {style.get('language', '')}"
        )

    return charter.strip() + "\n\n" + "\n\n".join(extras)
